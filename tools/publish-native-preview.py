#!/usr/bin/env python3
"""Publish freshly generated native screenshots to a revision-specific review branch.

This runs on the Mac that generated the screenshots. It does not download or
relay Actions artifacts. The branch preserves the exact source revision under
review, and never changes main or overwrites an existing review branch.
"""
import base64
import json
import os
import re
import urllib.error
import urllib.request
from pathlib import Path


def main():
    repository = os.environ['GITHUB_REPOSITORY']
    revision = os.environ['GITHUB_SHA']
    if not re.fullmatch(r'[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+', repository) or not re.fullmatch(r'[0-9a-f]{40}', revision):
        raise SystemExit('Invalid repository/revision')
    folder = Path('preview-screenshots')
    pictures = sorted(folder.glob('*.png'))
    if not pictures:
        print('No native screenshots were generated; no review branch created.')
        return

    def api(path, data=None):
        request = urllib.request.Request('https://api.github.com/repos/' + repository + '/' + path,
                                        data=None if data is None else json.dumps(data).encode(),
                                        headers={'Authorization': 'Bearer ' + os.environ['GITHUB_TOKEN'],
                                                 'Accept': 'application/vnd.github+json', 'Content-Type': 'application/json'})
        with urllib.request.urlopen(request, timeout=60) as response:
            return json.load(response)

    if api('git/ref/heads/main')['object']['sha'] != revision:
        print('A newer source revision exists; retaining artifacts without publishing stale review images.')
        return
    branch = 'review/native-' + revision[:10]
    try:
        api('git/ref/heads/' + branch)
        print('A native review branch already exists for this source revision.')
        return
    except urllib.error.HTTPError as error:
        if error.code != 404:
            raise

    entries = []
    for picture in pictures:
        blob = api('git/blobs', {'encoding': 'base64', 'content': base64.b64encode(picture.read_bytes()).decode('ascii')})
        entries.append({'path': 'docs/native-preview/' + picture.name, 'mode': '100644', 'type': 'blob', 'sha': blob['sha']})
    description = '# Native simulator review\n\nSource revision: `' + revision + '`\n\n'
    description += 'Generated by the iPad Simulator from the actual SwiftUI sources.\n'
    description += 'Desktop showcase content uses a local HTML page. Control review is simulator-only.\n'
    description += 'Display orientation is normalized for review; raw captures remain in the Actions artifact.\n'
    description += 'Screenshots do not validate LiveContainer guest compatibility.\n\n'
    for picture in pictures:
        description += '![' + picture.stem + '](' + picture.name + ')\n\n'
    entries.append({'path': 'docs/native-preview/README.md', 'mode': '100644', 'type': 'blob', 'content': description})
    source = api('git/commits/' + revision)
    tree = api('git/trees', {'base_tree': source['tree']['sha'], 'tree': entries})
    commit = api('git/commits', {'message': 'Record native simulator screenshots for ' + revision[:10], 'tree': tree['sha'], 'parents': [revision]})
    api('git/refs', {'ref': 'refs/heads/' + branch, 'sha': commit['sha']})
    url = 'https://github.com/' + repository + '/tree/' + branch + '/docs/native-preview'
    print('Native screenshot review: ' + url)
    if os.environ.get('GITHUB_STEP_SUMMARY'):
        with open(os.environ['GITHUB_STEP_SUMMARY'], 'a') as summary:
            summary.write('Native screenshots for `' + revision[:10] + '`: [review images](' + url + ').\n')


if __name__ == '__main__':
    main()
